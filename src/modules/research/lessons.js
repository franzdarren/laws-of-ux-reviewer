export const BIASES = [
  {
    id: 'confirmation-bias',
    what: 'Looking for, noticing and remembering evidence that supports what you already believe.',
    eg: 'A designer only quotes the users who liked the redesign.',
    fix: 'Write hypotheses before research, look for evidence against them, and analyze with others.',
  },
  {
    id: 'false-consensus',
    what: 'Assuming other people think and act like you.',
    eg: '"I always use keyboard shortcuts, so our users will too."',
    fix: 'You are not the user. Test with real users from your target group.',
  },
  {
    id: 'leading-question',
    what: 'A question whose wording suggests the answer the researcher expects.',
    eg: '"How much easier is the new checkout?"',
    fix: 'Ask open, neutral questions: "Tell me about using the checkout."',
  },
  {
    id: 'social-desirability',
    what: 'Participants answer in the way that makes them look good.',
    eg: 'People say they read the terms and conditions.',
    fix: 'Watch behavior instead of asking; assure people there are no right answers; use anonymous surveys.',
  },
  {
    id: 'acquiescence',
    what: 'The tendency to agree with statements, or to say yes, regardless of content.',
    eg: 'Most people answer "Yes" to "Would you use this feature?"',
    fix: 'Avoid yes/no questions; mix positive and negative statements (as SUS does).',
  },
  {
    id: 'hawthorne',
    what: 'People change their behavior because they know they are being observed.',
    eg: 'Staff follow every step of the process only while a researcher is watching.',
    fix: 'Build rapport, stay in the background, observe longer, and combine with analytics.',
  },
  {
    id: 'sampling-bias',
    what: 'The people you study don\'t represent your real users.',
    eg: 'Testing an enrollment app only with IT students from your own block.',
    fix: 'Recruit across the user groups that matter: courses, years, devices, experience.',
  },
  {
    id: 'framing',
    what: 'The way information is presented changes people\'s answers.',
    eg: '"90% of users succeed" sounds better than "10% of users fail".',
    fix: 'Present options neutrally and consistently; vary order between participants.',
  },
  {
    id: 'survivorship',
    what: 'Studying only the people who "survived" a process and ignoring those who dropped out.',
    eg: 'Surveying only current users about why the app is good, not those who uninstalled it.',
    fix: 'Also research people who quit, churned or never signed up.',
  },
];

